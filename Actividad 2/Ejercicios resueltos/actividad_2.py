"""Ejercicio 2.5. Definición de métodos con parámetros: clase CuentaBancaria."""

from enum import Enum
class TipoCuenta(Enum):
    AHORROS = 1
    CORRIENTE = 2


class CuentaBancaria:

    def __init__(self, nombres_titular: str, apellidos_titular: str,
                 numero_cuenta: int, tipo_cuenta: TipoCuenta,
                 porcentaje_interes_mensual: float):
        self.nombres_titular = nombres_titular
        self.apellidos_titular = apellidos_titular
        self.numero_cuenta = numero_cuenta
        self.tipo_cuenta = tipo_cuenta
        self.saldo = 0.0
        self.porcentaje_interes_mensual = porcentaje_interes_mensual  # Propuesto

    def imprimir(self) -> None:
        print("Nombres del titular =", self.nombres_titular)
        print("Apellidos del titular =", self.apellidos_titular)
        print("Número de cuenta =", self.numero_cuenta)
        print("Tipo de cuenta =", self.tipo_cuenta.name)
        print("Saldo =", self.saldo)
        print("Interés mensual (%) =", self.porcentaje_interes_mensual)

    def consultar_saldo(self) -> None:
        print("El saldo actual es = $", self.saldo)

    def consignar(self, valor: float) -> bool:
        if valor > 0:
            self.saldo = self.saldo + valor
            print("Se ha consignado $", valor, "en la cuenta.",
                  "El nuevo saldo es $", self.saldo)
            return True
        print("El valor a consignar debe ser mayor que cero.")
        return False

    def retirar(self, valor: float) -> bool:
        if 0 < valor <= self.saldo:
            self.saldo = self.saldo - valor
            print("Se ha retirado $", valor, "de la cuenta.",
                  "El nuevo saldo es $", self.saldo)
            return True
        print("El valor a retirar debe ser mayor que cero y no superar el saldo.")
        return False

    def aplicar_interes(self) -> float:
        interes = self.saldo * self.porcentaje_interes_mensual / 100
        self.saldo = round(self.saldo + interes, 2)
        return self.saldo


def main() -> None:
    """Crea una cuenta y realiza consignaciones, retiros y aplica el interés."""
    cuenta = CuentaBancaria("Pedro", "Pérez", 123456789, TipoCuenta.AHORROS, 1.5)
    cuenta.imprimir()
    cuenta.consignar(200000)
    cuenta.consignar(300000)
    cuenta.retirar(400000)
    cuenta.retirar(500000)  # No se permite: supera el saldo
    print("Saldo con interés = $", cuenta.aplicar_interes())
    cuenta.consultar_saldo()


if __name__ == "__main__":
    main()
import math
class Circulo:

    def __init__(self, radio: float):
        self.radio = radio

    def calcular_area(self) -> float:
        return math.pi * self.radio ** 2

    def calcular_perimetro(self) -> float:
        return 2 * math.pi * self.radio


class Rectangulo:

    def __init__(self, base: float, altura: float):
        self.base = base
        self.altura = altura

    def calcular_area(self) -> float:
        return self.base * self.altura

    def calcular_perimetro(self) -> float:
        return (2 * self.base) + (2 * self.altura)


class Cuadrado:

    def __init__(self, lado: float):
        self.lado = lado

    def calcular_area(self) -> float:
        return self.lado * self.lado

    def calcular_perimetro(self) -> float:
        return 4 * self.lado


class TrianguloRectangulo:

    def __init__(self, base: float, altura: float):
        self.base = base
        self.altura = altura

    def calcular_area(self) -> float:
        return self.base * self.altura / 2

    def calcular_perimetro(self) -> float:
        return self.base + self.altura + self.calcular_hipotenusa()

    def calcular_hipotenusa(self) -> float:
        return math.sqrt(self.base ** 2 + self.altura ** 2)

    def determinar_tipo_triangulo(self) -> None:
        hipotenusa = self.calcular_hipotenusa()
        if self.base == self.altura and self.base == hipotenusa:
            print("Es un triángulo equilátero")  # Todos sus lados son iguales
        elif (self.base != self.altura and self.base != hipotenusa
              and self.altura != hipotenusa):
            print("Es un triángulo escaleno")    # Todos sus lados son diferentes
        else:
            print("Es un triángulo isósceles")   # Tiene dos lados iguales


class Rombo:

    def __init__(self, diagonal_mayor: float, diagonal_menor: float):
        self.diagonal_mayor = diagonal_mayor
        self.diagonal_menor = diagonal_menor

    def calcular_lado(self) -> float:
        return math.sqrt((self.diagonal_mayor / 2) ** 2
                         + (self.diagonal_menor / 2) ** 2)

    def calcular_area(self) -> float:
        return self.diagonal_mayor * self.diagonal_menor / 2

    def calcular_perimetro(self) -> float:
        return 4 * self.calcular_lado()


class Trapecio:

    def __init__(self, base_mayor: float, base_menor: float,
                 lado_izquierdo: float, lado_derecho: float, altura: float):
        self.base_mayor = base_mayor
        self.base_menor = base_menor
        self.lado_izquierdo = lado_izquierdo
        self.lado_derecho = lado_derecho
        self.altura = altura

    def calcular_area(self) -> float:
        return (self.base_mayor + self.base_menor) * self.altura / 2

    def calcular_perimetro(self) -> float:
        return (self.base_mayor + self.base_menor
                + self.lado_izquierdo + self.lado_derecho)


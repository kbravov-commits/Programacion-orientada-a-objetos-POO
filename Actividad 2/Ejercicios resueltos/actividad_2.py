from enum import Enum


class TipoPlaneta(Enum):
    GASEOSO = 1
    TERRESTRE = 2
    ENANO = 3


class Planeta:
    UA_KM = 149_597_870  # Una unidad astronómica (UA) en kilómetros

    def __init__(self, nombre: str = None, cantidad_satelites: int = 0,
                 masa: float = 0.0, volumen: float = 0.0, diametro: int = 0,
                 distancia_sol: int = 0, tipo: TipoPlaneta = None,
                 es_observable: bool = False, periodo_orbital: float = 0.0,
                 periodo_rotacion: float = 0.0):
        self.nombre = nombre
        self.cantidad_satelites = cantidad_satelites
        self.masa = masa
        self.volumen = volumen
        self.diametro = diametro
        self.distancia_sol = distancia_sol
        self.tipo = tipo
        self.es_observable = es_observable
        self.periodo_orbital = periodo_orbital    # Ejercicio propuesto
        self.periodo_rotacion = periodo_rotacion  # Ejercicio propuesto

    def imprimir(self) -> None:
        print("Nombre del planeta =", self.nombre)
        print("Cantidad de satélites =", self.cantidad_satelites)
        print("Masa del planeta (kg) =", self.masa)
        print("Volumen del planeta (km³) =", self.volumen)
        print("Diámetro del planeta (km) =", self.diametro)
        print("Distancia al Sol (millones de km) =", self.distancia_sol)
        print("Tipo de planeta =", self.tipo.name)
        print("Es observable =", self.es_observable)
        print("Periodo orbital (años) =", self.periodo_orbital)
        print("Periodo de rotación (días) =", self.periodo_rotacion)

    def calcular_densidad(self) -> float:
        return self.masa / self.volumen

    def es_planeta_exterior(self) -> bool:
        limite = 3.4 * Planeta.UA_KM / 1_000_000  # En millones de km
        return self.distancia_sol > limite


